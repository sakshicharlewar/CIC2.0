import urllib.request
import re

req = urllib.request.urlopen('http://localhost:3000')
html = req.read().decode('utf-8', errors='ignore')
css_urls = re.findall(r'href="(/_next/static/css/[^"]+)"', html)
print('CSS URLs:', css_urls)

for cu in css_urls:
    c_req = urllib.request.urlopen('http://localhost:3000' + cu)
    css_content = c_req.read().decode('utf-8', errors='ignore')
    print(cu, 'Length:', len(css_content))
    has_43 = '4/3' in css_content
    print('4/3 in CSS:', has_43)
    if not has_43:
        print('WARNING: aspect-4/3 is NOT generated by Tailwind!')

